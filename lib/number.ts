/**
 * Разбор пользовательского ввода числа.
 * Принимает и точку, и запятую как десятичный разделитель,
 * игнорирует пробелы и неразрывные пробелы (их подставляет numpad).
 * Возвращает null для пустой строки и для неоднозначного ввода:
 * «3,5,2» превращается в «3.5.2», Number даёт NaN, и значение отклоняется.
 * Нужен именно null, а не 0, чтобы вызывающий код показал ошибку или
 * заблокировал кнопку, а не молча отправил неверное число.
 */
export function parseNumberInput(value: string): number | null {
  const normalized = value.replace(/\s/g, '').replace(/,/g, '.')
  if (normalized === '') return null
  const parsed = Number(normalized)
  return Number.isFinite(parsed) ? parsed : null
}

/**
 * Число → строка для поля ввода: десятичный разделитель всегда запятая,
 * чтобы загруженные из БД значения выглядели так же, как введённые вручную.
 * Ввод пользователя эта функция не касается: точки и запятые равноправны.
 */
export function toInputValue(
  n: number | null | undefined,
  fractionDigits?: number,
): string {
  if (n === null || n === undefined || Number.isNaN(n)) return ''
  const s = fractionDigits != null ? n.toFixed(fractionDigits) : String(n)
  return s.replace('.', ',')
}

/**
 * Очистка ввода: оставляем цифры и разделители ровно в том виде, в каком
 * они набраны, всё остальное отбрасываем. Точка в запятую НЕ переводится:
 * пользователь должен видеть то, что сам ввёл.
 *
 * Единственный разделитель здесь сознательно не проверяем. Иначе лишний
 * символ пришлось бы вырезать молча, и «3,5,2» тихо превратился бы в
 * «3,52» — правдоподобное, но другое число. Вместо этого значение с двумя
 * разделителями остаётся в поле как есть и отсекается парсером:
 * parseNumberInput вернёт null, и отправка будет заблокирована.
 *
 * Ведущий разделитель сохраняется — иначе «,5» с мобильной клавиатуры
 * превратилось бы в «5» вместо «0,5». Минус отбрасывается: во всех полях
 * min=0. Пустая строка и одиночный разделитель допустимы как промежуточные
 * состояния при наборе; парсер вернёт для них null.
 */
export function sanitizeNumericInput(raw: string): string {
  let out = ''

  for (const char of raw) {
    if ((char >= '0' && char <= '9') || char === ',' || char === '.') {
      out += char
    }
  }

  return out
}
